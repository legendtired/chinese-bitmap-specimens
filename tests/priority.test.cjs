const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {filterCatalog} = require('../app.js');
const rows = require('../data/catalog.json');
const expected = ['founder_pixel12','apple_kai_12','mingliu_native_13','firefly_sung_14','renoufangsong-16','hbf_Beijing16','kh_dot_ningyouchou_16_16px','sony-g90-original','hanyi-pixel13','hanyi-pixel-xingkai15','psa_c_screen_12'];
const snapshot = JSON.stringify(rows);
const context = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../data/catalog.js'),'utf8'),context);
assert.equal(JSON.stringify(context.window.FONT_CATALOG),snapshot,'JS and JSON catalog must match');
assert.equal(rows.length,require('../data/release-psa.json').totalRows);
assert(rows.every(row=>typeof row.priority==='number'&&Number.isFinite(row.priority)));
assert.equal(rows.filter(row=>row.priority>0).length,11);
for (const [index,id] of expected.entries()) assert.equal(rows.find(row=>row.id===id).priority,index<8 ? 90-index*10 : index===8 ? 10 : index===9 ? 9 : 8);
for (const row of rows.filter(row=>!expected.includes(row.id))) assert.equal(row.priority,0);
const ids = list => list.map(row=>row.id);
assert.deepEqual(ids(filterCatalog(rows,{}).slice(0,11)),expected,'Default order is curated order');
assert.deepEqual(ids(filterCatalog(rows,{},'','recommended').slice(0,11)),expected);
const zeroed = rows.map(row=>({...row,priority:0}));
for (const mode of ['height','height-desc','name']) assert.deepEqual(ids(filterCatalog(rows,{},'',mode)),ids(filterCatalog(zeroed,{},'',mode)),`Manual ${mode} ignores priorities`);
assert.deepEqual(ids(filterCatalog(rows,{height:['12']})).slice(0,2),expected.slice(0,2));
assert(filterCatalog(rows,{height:['12']}).every(row=>require('../app.js').heightValue(row)==='12'));
assert.deepEqual(ids(filterCatalog(rows,{height:['16']})).slice(0,3),expected.slice(4,7));
const family = rows.find(row=>row.id===expected[0]).family;
assert(filterCatalog(rows,{},family).every(row=>row.family===family));
const tied=[{id:'c',name:'B',height:12,priority:10},{id:'a',name:'A',height:12,priority:10},{id:'b',name:'Z',height:8,priority:10}];
assert.deepEqual(ids(filterCatalog(tied,{})),['b','a','c']);
assert.deepEqual(ids(filterCatalog(tied.map(({priority,...row})=>row),{})),['b','a','c']);
assert.equal(JSON.stringify(rows),snapshot,'Filtering/sorting must not mutate catalog');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert(html.includes('<select id="sort"><option value="recommended" selected>推荐排序</option>'));
console.log('Priority tests passed: exact11/default order, original10 preserved and PSA12 appended, manual sort ignores weights, filters preserved, ties/missing weights stable, data JS/JSON identical.');
